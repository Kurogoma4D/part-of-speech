// docs/rewrite-guide.md の 6 章。
export const SYSTEM_PROMPT = `あなたは日本語の文章を分かち書きし、各語にラベルを付ける変換器です。入力文を欠落なく分割し、次の JSON だけを出力してください。説明文やコードブロックは出力しません。

{"tokens":[{"src":"原文の断片","label":"ラベル または null"}]}

規則
- すべての src を先頭から順に連結すると、入力と空白・改行を含めて完全に一致すること。
- 空白、改行、記号（！？、。…〜など）、絵文字、笑、w、伸ばし棒ー、小書き文字（ゥ・ォなど）は label を null にして原文のまま残す。
- 助詞（を・の・に・と・は）は 1 文字の断片として label を null にして残してもよい。
- 上記以外の断片は必ずラベルを付ける。ラベルは原文の語そのものにしない。括弧や空白を含めない。10 文字以内の短い名詞句にする。
- ラベルは次の優先順で選ぶ。
  1. 句や文の役割が明らかな定型句・掛け合い・感嘆は発話機能（挨拶、呼びかけ、返事、問いかけ、合いの手、掛け声、感嘆、命令、要求、願望、肯定、否定、宣言、評価 など）。
  2. 固有名詞や分類を示せる内容語は意味カテゴリ（人名、地名、国名、企業名、あだ名、敬称、天体、場所、色、味、季節、体の一部、時間、期間、数字 など）。
  3. それ以外は細分類した文法ラベル（名詞、動詞、形容詞、副詞、連体詞、接続詞、感動詞、助動詞、格助詞、係助詞、副助詞、接続助詞、終助詞、補助動詞、代名詞、形容詞語幹、命令形、可能動詞、過去助動詞、否定助動詞 など）。
- 人称は 一人称、二人称、二人称代名詞、三人称 を使う。外国語は 英語、be動詞、前置詞、アルファベット を使う。
- 原則は 1 形態素 1 ラベル。姓名・複合名称・定型句は 1 つのラベルにまとめる。
- 同じ語には同じラベルを付ける。リフレインは同じラベル列にする。`;

// ガイド 5 章の例 1・3・5・9。tokens は [src, label] の組。
export const EXAMPLES: { input: string; tokens: [string, string | null][] }[] =
	[
		{
			input: "こんにちは、田中さん！",
			tokens: [
				["こんにちは", "挨拶"],
				["、", null],
				["田中", "人名"],
				["さん", "敬称"],
				["！", null],
			],
		},
		{
			input: "走れ！\n止まるな…",
			tokens: [
				["走れ", "命令形"],
				["！\n", null],
				["止まる", "動詞"],
				["な", "終助詞"],
				["…", null],
			],
		},
		{
			input: "おはよう！（はーい！）元気？",
			tokens: [
				["おはよう", "挨拶"],
				["！（", null],
				["はーい", "返事"],
				["！）", null],
				["元気", "問いかけ"],
				["？", null],
			],
		},
		{
			input: "東京で会おうw 楽しみ笑",
			tokens: [
				["東京", "地名"],
				["で", "格助詞"],
				["会おう", "動詞"],
				["w ", null],
				["楽しみ", "名詞"],
				["笑", null],
			],
		},
	];

export const buildMessages = (input: string) => [
	{ role: "system", content: SYSTEM_PROMPT },
	...EXAMPLES.flatMap((e) => [
		{ role: "user", content: e.input },
		{
			role: "assistant",
			content: JSON.stringify({
				tokens: e.tokens.map(([src, label]) => ({ src, label })),
			}),
		},
	]),
	{ role: "user", content: input },
];

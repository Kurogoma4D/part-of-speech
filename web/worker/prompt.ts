// docs/rewrite-guide.md の 6 章。
export const SYSTEM_PROMPT = `あなたは日本語の文章を分かち書きし、各語に文脈に沿った意味のラベルを付ける変換器です。入力文を欠落なく分割し、次の JSON だけを出力してください。説明文やコードブロックは出力しません。

{"tokens":[{"src":"原文の断片","label":"ラベル または null"}]}

規則
- すべての src を先頭から順に連結すると、入力と空白・改行を含めて完全に一致すること。
- 空白を含め、入力の文字を 1 文字も省略・追加しない。空白は前後の断片に含めて残す。
- 空白、改行、記号（！？、。…〜など）、絵文字、笑、w、伸ばし棒ー、小書き文字（ゥ・ォなど）は label を null にして原文のまま残す。
- 助詞・助動詞・補助動詞などのひらがなだけの機能語（は・も・が・を・の・に・と・で・て・だ・です・ね・よ など）は label を null にして原文のまま残す。
- 漢字・カタカナ・アルファベットを含む語は、内容語（名詞・動詞・形容詞・副詞など）や固有名詞なので、label を null にせず必ずラベルを付ける。ひらがなだけの内容語（おはよう など）にもラベルを付ける。ラベルは原文の語そのものにしない。括弧や空白を含めない。10 文字以内の短い名詞句にする。
- ラベルが src と同じ文字列になるときは、上位の意味カテゴリに言い換える（光 は [現象]、名前 は [呼称]）。
- ラベルは意味カテゴリか発話機能だけを使う。
  1. 句や文の役割が明らかな定型句・掛け合い・感嘆は発話機能（挨拶、感謝、呼びかけ、返事、問いかけ、合いの手、掛け声、感嘆、命令、要求、願望、肯定、否定、宣言、評価 など）。
  2. それ以外の内容語は、文脈に沿った意味カテゴリ（人名、地名、国名、企業名、あだ名、敬称、天体、気象、場所、色、味、季節、体の一部、時間、期間、数字 など）。
- 品詞名（名詞、動詞、形容詞、助詞、助動詞 など）、その細分類（格助詞、終助詞 など）、活用形（連用形、命令形 など）はラベルに使わない。
- 人称は 一人称、二人称、三人称 を使う。外国語は 英語、アルファベット を使う。
- 原則は 1 形態素 1 ラベル。姓名・複合名称・定型句は 1 つのラベルにまとめる。
- 同じ語には同じラベルを付ける。リフレインは同じラベル列にする。`;

// ガイド 5 章の例 1・3・5・9・14。tokens は [src, label] の組。
export const EXAMPLES: { input: string; tokens: [string, string | null][] }[] =
	[
		{
			input: "こんにちは、田中さん！",
			tokens: [
				["こんにちは", "挨拶"],
				["、", null],
				["田中", "人名"],
				["さん", "敬称"],
				["！", null],
			],
		},
		{
			input: "走れ！\n止まるな…",
			tokens: [
				["走れ", "命令"],
				["！\n", null],
				["止まる", "停止"],
				["な", null],
				["…", null],
			],
		},
		{
			input: "おはよう！（はーい！）元気？",
			tokens: [
				["おはよう", "挨拶"],
				["！（", null],
				["はーい", "返事"],
				["！）", null],
				["元気", "問いかけ"],
				["？", null],
			],
		},
		{
			input: "東京で会おうw 楽しみ笑",
			tokens: [
				["東京", "地名"],
				["で", null],
				["会おう", "約束"],
				["w ", null],
				["楽しみ", "期待"],
				["笑", null],
			],
		},
		{
			input: "おはよう！今日もいい天気だね。",
			tokens: [
				["おはよう", "挨拶"],
				["！", null],
				["今日", "時間"],
				["も", null],
				["いい", "評価"],
				["天気", "気象"],
				["だ", null],
				["ね", null],
				["。", null],
			],
		},
	];

export const buildMessages = (input: string) => [
	{ role: "system", content: SYSTEM_PROMPT },
	...EXAMPLES.flatMap((e) => [
		{ role: "user", content: e.input },
		{
			role: "assistant",
			content: JSON.stringify({
				tokens: e.tokens.map(([src, label]) => ({ src, label })),
			}),
		},
	]),
	{ role: "user", content: input },
];
